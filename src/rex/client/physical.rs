//! Explicit W3C physical-code mapping from Rex API revision 7 client.key.
//! Unknown hardware names never fall back to the layout's logical character.
pub(super) fn protocol_key(code: &str) -> &'static str {
    CODES
        .iter()
        .find_map(|(physical, wire)| (*physical == code).then_some(*wire))
        .unwrap_or("unidentified")
}

